    @classmethod
    def get_law(cls, law_number: int) -> str:
        """Возвращает текст закона по его номеру."""
        return cls.LAWS.get(law_number, "Закон не найден.")

    @classmethod
    def get_all_laws(cls) -> Dict[int, str]:
        """Возвращает полный свод законов."""
        return cls.LAWS if hasattr(cls, 'LAWS') else cls.LAWS

    @classmethod
    def validate_action(cls, action_context: Dict[str, Any]) -> bool:
        """
        Базовая проверка действия на соответствие конституции.
        """
        if action_context.get("destructive", False) and not action_context.get("override_approved", False):
            return False
        return True
