from typing import List, Dict

class PersuasionEngine:
    """
    Движок психологического превосходства DonMir.
    Превращает физические улики износа в инструменты манипуляции и убеждения.
    """

    @staticmethod
    def get_strategy(category: str, defects: List[str], urgency_detected: bool) -> Dict[str, Any]:
        """
        Формирует тактику переговоров на основе 'улик' и психотипа сделки.
        """
        tactics = []
        
        # 1. Техника 'Визуальное Обесценивание' (на основе твоих примеров)
        if defects:
            tactics.append({
                "name": "The Physical Evidence Gambit",
                "action": "Укажите на руль/педали. Сравните их износ с заявленным пробегом.",
                "phrase": f"Смотрите, состояние руля и педалей говорит о пробеге в два раза выше. Это ставит под сомнение всю остальную историю машины."
            })

        # 2. Техника 'Релятивное Якорение'
        tactics.append({
            "name": "Anchoring",
            "action": "Назовите цену на 30% ниже рынка, обосновав её стоимостью 'восстановления до идеала'.",
            "phrase": "Я хочу купить, но чтобы привести её в чувство после такого износа салона, мне нужно вложить $X. Мое предложение — $Y."
        })

        # 3. Техника 'Дефицит времени' (если продавец спешит)
        if urgency_detected:
            tactics.append({
                "name": "The Reluctant Buyer",
                "action": "Покажите, что вы — единственный, кто приехал с деньгами прямо сейчас.",
                "phrase": "Я вижу, вам нужно решить вопрос сегодня. Я готов забрать за наличные в течение часа, но только по цене $Z. Выбор за вами."
            })

        return {
            "strategies": tactics,
            "tone": "Спокойный, экспертный, слегка разочарованный (вызывает у продавца чувство вины за состояние товара)."
        }
